// Generates dates relative to today for realistic 7-day dashboard charts
const now = new Date();
const daysAgo = (days: number, hours = 0) => {
  const d = new Date(now);
  d.setDate(d.getDate() - days);
  d.setHours(d.getHours() - hours);
  return d;
};

